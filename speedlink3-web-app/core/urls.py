from django.contrib import admin
from django.urls import path
from django.conf import settings
from django.conf.urls.static import static
from cms import views

urlpatterns = [
    path('admin/', admin.site.urls),
    path('', views.home_view, name='home'),
    path('about/', views.about_view, name='about'),
    path('services/', views.services_view, name='services'),
    path('contact/', views.contact_view, name='contact'),
    path('insights/', views.insights_view, name='insights'),
    path('insights/<slug:slug>/', views.post_detail_view, name='post_detail'),
    path('page/<slug:slug>/', views.page_detail_view, name='page_detail'),
    path('api/posts/', views.api_posts_list, name='api_posts'),
    path('api/chat/', views.ai_chat_agent_api, name='api_chat'),
    path('signup/', views.signup_view, name='signup'),
    path('login/', views.login_view, name='login'),
    path('logout/', views.logout_view, name='logout'),
    path('google-auth-callback/', views.google_auth_callback, name='google_auth_callback'),
    path('admin/dashboard/', views.dashboard_view, name='dashboard'),
]

if settings.DEBUG:
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)
    urlpatterns += static(settings.STATIC_URL, document_root=settings.STATIC_ROOT)

